/**
 * Human-takeover guard for DMs - added 2026-09-24 (Ravi).
 *
 * Ravi's ask: "if a human (not the AI) replies in a DM, the AI should go
 * quiet - just monitor and log, not reply - until the customer gets no
 * human reply for 4 working hours, at which point the AI takes back over as
 * a stand-in, reassuring the customer the team will definitely reply."
 * Scoped to DMs only, per Ravi's own wording ("kisi bhi Dm me") - public
 * comment threads are unaffected.
 *
 * HOW THIS WORKS (read before changing):
 * Zernio's webhook only fires for CUSTOMER-sent events (message.received) -
 * it never tells us when a human manually replies from Instagram/Zernio's
 * own inbox UI. There is no real-time signal for "a human just replied".
 *
 * So this piggybacks on traffic we already get: every time a new customer
 * DM arrives, we do ONE extra read of that conversation's most recent
 * messages (Zernio's listInboxConversationMessages - the same read API
 * api/backfill.js already uses) and check whether the latest "outgoing"
 * message in there was one WE sent. We know what we sent because every
 * AI-sent reply is fingerprinted into Redis right after sending (see
 * markAiSent, called from api/webhook.js). If the latest outgoing message
 * doesn't match a fingerprint we hold, it wasn't generated by this bot - a
 * human must have typed it directly into Instagram/Zernio.
 *
 * This deliberately avoids a cron/scheduled-poll design across every
 * conversation (Vercel's cron frequency and Zernio's own API limits are
 * both unverified from here, and constantly polling every conversation
 * would multiply API calls even during quiet periods). This only costs one
 * extra Zernio read per incoming customer DM, which we're already
 * processing anyway.
 *
 * HARD LIMITATION Ravi confirmed and should keep in mind: this can only
 * ever detect a human reply that happens INSIDE the same Instagram/WhatsApp
 * thread. A phone call (which Ravi confirmed the team also uses, e.g. the
 * seller flow's "Neel ji aapko call karenge") leaves no trace here and can
 * never be detected by this or any other code - there is no way to build
 * around that with the tools available.
 */

const crypto = require('crypto');
const { listInboxConversationMessages } = require('./zernioClient');

function redisConfig() {
  return {
    url: (process.env.REDIS_KV_REST_API_URL || process.env.REDIS_URL || '').replace(/\/$/, ''),
    token: process.env.REDIS_KV_REST_API_TOKEN || process.env.REDIS_K_TOKEN || '',
  };
}

async function redisCommand(path) {
  const { url, token } = redisConfig();
  if (!url || !token) throw new Error('Redis credentials are not configured');
  const res = await fetch(`${url}${path}`, { headers: { Authorization: `Bearer ${token}` } });
  if (!res.ok) throw new Error(`Redis error ${res.status}`);
  return res.json().catch(() => ({}));
}

function textHash(text) {
  return crypto.createHash('sha256').update(String(text || '').trim().toLowerCase().replace(/\s+/g, ' ')).digest('hex').slice(0, 24);
}

// FIX 2026-09-30 (Ravi): was 24h. The baseline below lives 7 days, so a
// customer returning 1-7 days after Mannat's last reply found that reply's
// fingerprint EXPIRED, mistook Mannat's own old message for a human reply,
// and silenced her (caught in a live Instagram test). Fingerprints must
// always outlive the baseline window - 30 days does.
const AI_SENT_TTL_SECONDS = 30 * 24 * 60 * 60;
const HUMAN_ACTIVE_TTL_SECONDS = 7 * 24 * 60 * 60;

// Called from api/webhook.js right after an AI reply is successfully sent,
// so future takeover checks recognise it as our own message rather than
// mistaking it for a human reply.
async function markAiSent(memoryId, text) {
  try {
    await redisCommand(`/set/${encodeURIComponent(`gemrishi:ai-sent:${memoryId}:${textHash(text)}`)}/1/EX/${AI_SENT_TTL_SECONDS}`);
  } catch (err) {
    console.error('[humanTakeoverGuard] markAiSent failed:', err.message);
  }
}

// 2026-10-17: a DM Mannat sends to a commenter (private reply) lands in a
// conversation whose id we don't know yet - fingerprint it account-wide so it
// is never mistaken for a team member's message.
async function markAiSentAnyChat(text) {
  await markAiSent('any-chat', text);
}

async function getHandoffState(memoryId) {
  try {
    const data = await redisCommand(`/get/${encodeURIComponent(`gemrishi:human-active:${memoryId}`)}`);
    if (!data?.result) return null;
    return JSON.parse(data.result);
  } catch (err) {
    console.error('[humanTakeoverGuard] getHandoffState failed:', err.message);
    return null;
  }
}

async function setHandoffState(memoryId, state) {
  try {
    await redisCommand(`/set/${encodeURIComponent(`gemrishi:human-active:${memoryId}`)}/${encodeURIComponent(JSON.stringify(state))}/EX/${HUMAN_ACTIVE_TTL_SECONDS}`);
  } catch (err) {
    console.error('[humanTakeoverGuard] setHandoffState failed:', err.message);
  }
}

async function clearHandoffState(memoryId) {
  try {
    await redisCommand(`/del/${encodeURIComponent(`gemrishi:human-active:${memoryId}`)}`);
  } catch (err) {
    console.error('[humanTakeoverGuard] clearHandoffState failed:', err.message);
  }
}

// Working-hours math - 10 AM - 8 PM IST, all 7 days (same window as the
// handoff note in api/webhook.js). IST has no DST, fixed +5:30, so a plain
// offset is safe without a timezone library.
const IST_OFFSET_MINUTES = 5 * 60 + 30;
const WORK_START_MIN = 10 * 60;
const WORK_END_MIN = 20 * 60;
const RESUME_AFTER_WORKING_MINUTES = 4 * 60; // 4 working hours, per Ravi

// Minutes of *working-hours* time (10AM-8PM IST) that have elapsed between
// two real instants - a plain wall-clock diff would overcount overnight
// gaps, which matters since the whole point is "4 working hours", not
// "4 calendar hours".
function workingMinutesElapsed(fromMs, toMs) {
  if (toMs <= fromMs) return 0;
  let cursor = fromMs;
  let total = 0;
  let guard = 0;
  while (cursor < toMs && guard < 60) { // safety cap - never loop more than ~2 months of days
    guard += 1;
    const istMs = cursor + IST_OFFSET_MINUTES * 60000;
    const istDate = new Date(istMs);
    const dayStartIstMs = Date.UTC(istDate.getUTCFullYear(), istDate.getUTCMonth(), istDate.getUTCDate(), 0, 0, 0);
    const windowStart = dayStartIstMs + WORK_START_MIN * 60000 - IST_OFFSET_MINUTES * 60000;
    const windowEnd = dayStartIstMs + WORK_END_MIN * 60000 - IST_OFFSET_MINUTES * 60000;
    const segStart = Math.max(cursor, windowStart);
    const segEnd = Math.min(toMs, windowEnd);
    if (segEnd > segStart) total += (segEnd - segStart) / 60000;
    const nextWindowStart = windowStart + 24 * 60 * 60000;
    cursor = cursor < windowEnd ? windowEnd : nextWindowStart;
  }
  return total;
}

/**
 * Checks this DM conversation for a human-authored outgoing message and
 * returns the current takeover decision for the customer message that just
 * arrived.
 *
 * Returns { silence, justDetectedHuman, resumed }:
 *   - silence=true  -> api/webhook.js must NOT generate/send an AI reply.
 *   - justDetectedHuman=true -> a human message was found just now (useful
 *     for logging/notes).
 *   - resumed=true -> 4 working hours passed with no further human reply;
 *     the handoff state was cleared and normal AI replies resume.
 */
// Hard timeout on the Zernio read below - added after a live test showed
// this call can hang and silently block a customer from ever getting a
// reply (nothing else in this new code path had a safety net for that).
// zernioClient.js's requests had no built-in timeout/cancellation at all,
// unlike every other outbound call in this codebase (see
// escalationNotifier.js's postAppsScriptEmail/postWebhook/postTelegram, all
// AbortController-guarded) - it now accepts an optional signal, used here.
// If this ever times out or errors, we fail OPEN (treat as no takeover) - a
// slow/broken read must never be the reason a customer doesn't get a reply.
const ZERNIO_READ_TIMEOUT_MS = 5000;

// BASELINE - added after a live test caught a launch-day bug: every
// conversation that already had history BEFORE this feature existed has AI
// replies that were never fingerprinted (markAiSent only started running
// today). So the very first customer message on any pre-existing
// conversation would find the last AI reply has no fingerprint, wrongly
// read that as "a human sent this", and silence the bot - on literally
// every ongoing conversation at once, not just a genuine handoff.
//
// Fix: the first time we ever check a given conversation, we don't have
// enough fingerprint history to trust a "no match" result, so we establish
// a baseline and skip the human/AI comparison for THIS turn only (also
// wiping any stale handoff state a prior, buggy run may have set) - normal
// AI replies proceed, and that reply's own send gets fingerprinted via
// markAiSent as usual. From the customer's NEXT message onward, detection
// is fully reliable. This costs exactly one silently-skipped check per
// conversation, ever - a far safer default than silencing on a guess.
// v2 (2026-09-30): renamed key so every conversation re-baselines once after
// the 24h-fingerprint fix, which also wipes any handoff state wrongly set by
// that bug. Genuine human handoffs are re-detected from the next human reply.
async function hasBaseline(memoryId) {
  try {
    const data = await redisCommand(`/get/${encodeURIComponent(`gemrishi:takeover-baseline-v2:${memoryId}`)}`);
    return Boolean(data?.result);
  } catch (err) {
    console.error('[humanTakeoverGuard] baseline check failed; treating as no baseline (safe default):', err.message);
    return false;
  }
}

async function establishBaseline(memoryId) {
  try {
    await redisCommand(`/set/${encodeURIComponent(`gemrishi:takeover-baseline-v2:${memoryId}`)}/1/EX/${HUMAN_ACTIVE_TTL_SECONDS}`);
  } catch (err) {
    console.error('[humanTakeoverGuard] establishBaseline failed:', err.message);
  }
}

// =============================================================================
// FIX 2026-10-24 (Ravi, 3rd time Mannat talked over the team): the old check
// only looked at the LATEST outgoing TEXT message and compared it with
// Mannat's fingerprints. It missed:
//   - a team member sending a PHOTO / video / voice note (empty text -> skipped),
//   - a team reply followed by Mannat's own reply (the human one was no
//     longer "latest"),
//   - the first customer message in a new chat (baseline turn always skipped).
// Zernio now tells us HOW each outgoing message was sent: Mannat's go out via
// the API (sentVia: "api"); a person typing in the WhatsApp Business app or
// the Instagram app shows up without it (metadata.source e.g.
// "whatsapp_business_app"). So: any outgoing message in the last 7 days that
// Mannat did not send = a human is on this chat -> Mannat stays quiet.
// =============================================================================
const HUMAN_LOOKBACK_MS = 7 * 24 * 60 * 60 * 1000;

function sentViaOf(m) {
  return String(m?.sentVia || m?.metadata?.sentVia || '').toLowerCase();
}

function isOutgoing(m) {
  return ['outgoing', 'out', 'sent', 'outbound'].includes(String(m?.direction || '').toLowerCase());
}

function messageTimeMs(m) {
  const t = Date.parse(m?.sentAt || m?.createdAt || m?.timestamp || '');
  return Number.isFinite(t) ? t : 0;
}

// true = a person (not Mannat) sent this outgoing message.
// isLatestOutgoing: the newest outgoing message in the chat. A message with
// no "sent from an app" signal is only judged by Mannat's fingerprints when it
// is the newest one (the old, proven rule) - so a small text difference in an
// older Mannat message can never silence her by mistake.
async function isHumanMessage(memoryId, m, { isLatestOutgoing = true } = {}) {
  const text = String(m?.message || m?.text || '').trim();
  const hasMedia = Array.isArray(m?.attachments) && m.attachments.length > 0;
  if (!text && !hasMedia) return false; // nothing there (e.g. a reaction)
  if (text) {
    const ours = await isAiSent(memoryId, text).catch(() => null);
    if (ours === true) return false; // Mannat's own words
    if (ours === null) return false; // can't tell (Redis down) - fail open
  }
  const via = sentViaOf(m);
  const source = String(m?.metadata?.source || '').toLowerCase();
  if (source && source !== 'api') return true; // typed in the WhatsApp/Instagram app
  if (via && via !== 'api') return true;       // sent by a person, not our API
  if (!text) return true;                      // media - Mannat never sends media
  return isLatestOutgoing;                     // unknown text: old latest-only rule
}

// Latest human outgoing message time (ms) in the recent page, or 0.
async function latestHumanReplyMs({ apiKey, conversationId, accountId, memoryId, timeoutMs = ZERNIO_READ_TIMEOUT_MS }) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  let page;
  try {
    page = await listInboxConversationMessages({ apiKey, conversationId, accountId, limit: 30, sortOrder: 'desc', signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
  const messages = Array.isArray(page?.messages) ? page.messages : [];
  const now = Date.now();
  let latest = 0;
  let seenOutgoing = false;
  for (const m of messages) {
    if (!isOutgoing(m)) continue;
    const isLatestOutgoing = !seenOutgoing;
    seenOutgoing = true;
    const t = messageTimeMs(m) || now;
    if (now - t > HUMAN_LOOKBACK_MS) continue;
    if (t <= latest) continue;
    if (await isHumanMessage(memoryId, m, { isLatestOutgoing })) latest = t;
  }
  return latest;
}

async function checkHumanTakeover({ apiKey, conversationId, accountId, memoryId }) {
  if (!(await hasBaseline(memoryId))) await establishBaseline(memoryId); // kept for old callers/tests

  let lastHumanMs = 0;
  try {
    lastHumanMs = await latestHumanReplyMs({ apiKey, conversationId, accountId, memoryId });
  } catch (err) {
    console.error('[humanTakeoverGuard] Zernio read failed; using stored state only:', err.message);
  }

  const state = await getHandoffState(memoryId);
  const knownHumanMs = Date.parse(state?.lastHumanAt || state?.since || '') || 0;

  if (lastHumanMs && (!state || lastHumanMs > knownHumanMs + 1000)) {
    // A team member replied (again) - quiet now, restart the waiting clock.
    await setHandoffState(memoryId, { since: new Date().toISOString(), lastHumanAt: new Date(lastHumanMs).toISOString(), pendingSince: null });
    return { silence: true, justDetectedHuman: true, resumed: false };
  }

  if (!state || state.resumed) return { silence: false, justDetectedHuman: false, resumed: false };

  // A team member is handling this chat and the customer wrote again.
  const now = Date.now();
  if (!state.pendingSince) {
    await setHandoffState(memoryId, { ...state, pendingSince: new Date().toISOString() });
    return { silence: true, justDetectedHuman: false, resumed: false };
  }
  const elapsed = workingMinutesElapsed(new Date(state.pendingSince).getTime(), now);
  if (elapsed >= RESUME_AFTER_WORKING_MINUTES) {
    // Nobody answered for 4 working hours - Mannat steps back in. Remember
    // the human reply we already handled so it doesn't silence her again.
    await setHandoffState(memoryId, { ...state, resumed: true, resumedAt: new Date().toISOString() });
    return { silence: false, justDetectedHuman: false, resumed: true };
  }
  return { silence: true, justDetectedHuman: false, resumed: false };
}

// Right before each of Mannat's bubbles: did a person reply in this chat
// since `sinceMs`? Short timeout, fails open (never blocks a reply on error).
async function humanRepliedSince({ apiKey, conversationId, accountId, memoryId, sinceMs }) {
  try {
    const t = await latestHumanReplyMs({ apiKey, conversationId, accountId, memoryId, timeoutMs: 2500 });
    if (t && t >= sinceMs) {
      await setHandoffState(memoryId, { since: new Date().toISOString(), lastHumanAt: new Date(t).toISOString(), pendingSince: null, source: 'pre-send check' });
      return true;
    }
  } catch (err) {
    console.error('[humanTakeoverGuard] pre-send check failed; sending:', err.message);
  }
  return false;
}

// =============================================================================
// FIX 2026-10-16 (Ravi): "Mannat didn't stop when a team member messaged on
// Instagram". The check above only runs when a CUSTOMER message arrives, and
// only looks at the LATEST outgoing message. So if a team member replied while
// Mannat was already generating/typing her answer (a 5-20 second window:
// burst wait + Gemini + typing pauses), Mannat still sent - and her message
// then became the "latest outgoing", hiding the team member's reply for good.
// The takeover was never detected and she kept replying.
//
// Zernio DOES send us `message.sent` for outgoing DMs (the header comment
// above predates that) - we were logging and ignoring them. Two additions:
//   1. recordOutgoingMessage(): every outgoing DM is checked against Mannat's
//      fingerprints the moment it happens; an unknown one = a human replied,
//      so the conversation goes quiet immediately, in real time.
//   2. isHumanActive(): checked right before each of Mannat's bubbles is
//      sent, so a reply that was mid-typing when the human jumped in is
//      dropped instead of talking over the team member.
// =============================================================================
async function isAiSent(memoryId, text) {
  for (const scope of [memoryId, 'any-chat']) {
    const data = await redisCommand(`/get/${encodeURIComponent(`gemrishi:ai-sent:${scope}:${textHash(text)}`)}`);
    if (data?.result) return true;
  }
  return false;
}

async function recordOutgoingMessage({ memoryId, text, message }) {
  const m = message || { message: text, direction: 'outgoing' };
  if (!m.direction) m.direction = 'outgoing';
  const body = String(m.message || m.text || text || '').trim();
  const hasMedia = Array.isArray(m.attachments) && m.attachments.length > 0;
  if (!memoryId || (!body && !hasMedia)) return { human: false, reason: 'empty' };
  let human;
  try {
    human = await isHumanMessage(memoryId, { ...m, message: body });
  } catch (err) {
    console.error('[humanTakeoverGuard] outgoing check failed:', err.message);
    return { human: false, reason: 'redis_error' };
  }
  if (!human) return { human: false, reason: 'ai_sent' };
  if (!(await hasBaseline(memoryId))) await establishBaseline(memoryId);
  const at = new Date(messageTimeMs(m) || Date.now()).toISOString();
  await setHandoffState(memoryId, { since: new Date().toISOString(), lastHumanAt: at, pendingSince: null, source: 'message.sent' });
  return { human: true, reason: 'human_reply' };
}

async function isHumanActive(memoryId) {
  const state = await getHandoffState(memoryId);
  return Boolean(state && !state.resumed);
}

